# One-time setup: runs Pharmacy POS on XAMPP's Apache as a Windows service.
# - Apache starts automatically with Windows and is restarted by Windows if it ever stops.
# - The POS is served at http://127.0.0.1:8000 and only this PC can open it.
# - XAMPP's MySQL is NOT used (the POS uses SQLite), so MySQL crashes cannot affect it.
# Run via setup-xampp-service.bat (it asks for administrator rights).

param([string]$Xampp = 'C:\xampp', [int]$Port = 8000)
$ErrorActionPreference = 'Stop'

function Ok($m)   { Write-Host "[OK] $m" -ForegroundColor Green }
function Warn($m) { Write-Host "[!]  $m" -ForegroundColor Yellow }
function Fail($m) { Write-Host "[X]  $m" -ForegroundColor Red; exit 1 }
function PortInUse($p) { [bool](Get-NetTCPConnection -State Listen -LocalPort $p -ErrorAction SilentlyContinue) }

$project  = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$public   = (Join-Path $project 'public') -replace '\\', '/'
$apache   = Join-Path $Xampp 'apache'
$httpd    = Join-Path $apache 'bin\httpd.exe'
$httpConf = Join-Path $apache 'conf\httpd.conf'
$phpIni   = Join-Path $Xampp 'php\php.ini'
$service  = 'Apache2.4'
$stamp    = Get-Date -Format 'yyyyMMdd-HHmmss'

if (-not (Test-Path $httpd)) { Fail "XAMPP Apache not found at $apache" }
if (-not (Test-Path (Join-Path $project 'vendor\autoload.php'))) { Fail "Run install.bat first (vendor folder missing)." }

# 1) Stop Apache if XAMPP Control Panel started it (it will come back as a service)
$svc = Get-Service $service -ErrorAction SilentlyContinue
if ($svc -and $svc.Status -eq 'Running') { Stop-Service $service -Force; Start-Sleep 2 }
Get-Process httpd -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
Start-Sleep 1

# 2) Port checks: a busy port is the No.1 reason Apache refuses to start
if (PortInUse $Port) { Fail "Port $Port is already used by another program. Close it or run with -Port 8080." }
$conf = Get-Content $httpConf -Raw
Copy-Item $httpConf "$httpConf.bak-$stamp"
if (PortInUse 80) {
    Warn 'Port 80 is used by another program; disabling XAMPP''s default port 80 so Apache can still start.'
    $conf = $conf -replace '(?m)^Listen 80\s*$', '#Listen 80  # disabled by Pharmacy POS setup (port in use)'
}
if (PortInUse 443) {
    Warn 'Port 443 is used by another program; disabling XAMPP''s SSL config so Apache can still start.'
    $conf = $conf -replace '(?m)^Include conf/extra/httpd-ssl.conf', '#Include conf/extra/httpd-ssl.conf  # disabled by Pharmacy POS setup'
}

# 3) Virtual host for the POS (local-only)
$vhost = @"
# Pharmacy POS - generated by tools\setup-xampp-service.ps1
Listen 127.0.0.1:$Port
<VirtualHost 127.0.0.1:$Port>
    ServerName pharmacy-pos.local
    DocumentRoot "$public"
    <Directory "$public">
        Options -Indexes +FollowSymLinks
        AllowOverride All
        Require local
    </Directory>
    ErrorLog "logs/pharmacy-pos-error.log"
    CustomLog "logs/pharmacy-pos-access.log" common
</VirtualHost>
"@
$vhostFile = Join-Path $apache 'conf\extra\pharmacy-pos.conf'
Set-Content -Path $vhostFile -Value $vhost -Encoding Ascii
if ($conf -notmatch 'conf/extra/pharmacy-pos.conf') {
    $conf = $conf.TrimEnd() + "`r`nInclude conf/extra/pharmacy-pos.conf`r`n"
}
[IO.File]::WriteAllText($httpConf, $conf)   # no BOM
Ok "Apache configured: http://127.0.0.1:$Port  ->  $public"

# 4) PHP OPcache for speed (backup php.ini first)
$ini = Get-Content $phpIni -Raw
Copy-Item $phpIni "$phpIni.bak-$stamp"
$ini = $ini -replace '(?m)^;zend_extension=opcache', 'zend_extension=opcache'
$ini = $ini -replace '(?m)^;opcache.enable=1', 'opcache.enable=1'
$ini = $ini -replace '(?m)^;opcache.memory_consumption=128', 'opcache.memory_consumption=128'
$ini = $ini -replace '(?m)^;?opcache.validate_timestamps=.*', 'opcache.validate_timestamps=1'
[IO.File]::WriteAllText($phpIni, $ini)
Ok 'PHP OPcache enabled'

# 5) Validate configuration before touching the service
$test = & $httpd -t 2>&1 | Out-String
if ($LASTEXITCODE -ne 0) {
    Copy-Item "$httpConf.bak-$stamp" $httpConf -Force
    Fail "Apache config test failed, original config restored:`n$test"
}
Ok 'Apache configuration test passed'

# 6) Install / configure the Windows service
if (-not (Get-Service $service -ErrorAction SilentlyContinue)) {
    & $httpd -k install -n $service | Out-Null
    Ok "Installed Windows service '$service'"
}
sc.exe config $service start= auto | Out-Null
sc.exe failure $service reset= 86400 actions= restart/5000/restart/10000/restart/30000 | Out-Null
Ok 'Service set to start automatically and restart itself on failure'

Start-Service $service
Start-Sleep 3

# 7) Laravel: point APP_URL at the new address and cache config for speed
$envFile = Join-Path $project '.env'
if (Test-Path $envFile) {
    $envText = Get-Content $envFile -Raw
    $envText = $envText -replace '(?m)^APP_URL=.*', "APP_URL=http://127.0.0.1:$Port"
    [IO.File]::WriteAllText($envFile, $envText)
}
$php = Join-Path $Xampp 'php\php.exe'
Push-Location $project
& $php artisan optimize:clear | Out-Null
& $php artisan optimize | Out-Null
Pop-Location
Ok 'Laravel caches rebuilt'

# 8) Check it really works
try {
    $r = Invoke-WebRequest -UseBasicParsing "http://127.0.0.1:$Port/login" -TimeoutSec 20
    if ($r.StatusCode -eq 200) { Ok "Pharmacy POS is running at http://127.0.0.1:$Port" }
} catch {
    Fail "Apache started but the POS did not answer. See $apache\logs\pharmacy-pos-error.log"
}

Write-Host ''
Write-Host 'Done. You no longer need the XAMPP Control Panel. Use the "Pharmacy POS" desktop shortcut.' -ForegroundColor Cyan
Write-Host 'Do NOT start MySQL in XAMPP - the POS does not need it.' -ForegroundColor Cyan
